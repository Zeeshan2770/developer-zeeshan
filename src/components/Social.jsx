// Works out which icon/brand colour to use from the label (e.g. "Instagram", "X / Twitter", "My YouTube").
export const brandOf = (label = '') => {
  const l = label.toLowerCase();
  if (l.includes('github')) return 'github';
  if (l.includes('linkedin')) return 'linkedin';
  if (l.includes('insta')) return 'instagram';
  if (l.includes('facebook') || l === 'fb') return 'facebook';
  if (l.includes('twitter') || l === 'x' || l.startsWith('x ') || l.includes('x /')) return 'twitter';
  if (l.includes('youtube')) return 'youtube';
  if (l.includes('whatsapp')) return 'whatsapp';
  if (l.includes('mail')) return 'email';
  return 'link';
};

export default function SocialButtons({ links, large = false, className = '' }) {
  if (!links || links.length === 0) return null;
  return (
    <div className={`social-row${large ? ' lg' : ''} ${className}`} role="list" aria-label="Social profiles">
      {links.map((x) => {
        const brand = brandOf(x.label);
        const external = !x.url.startsWith('mailto:');
        return (
          <a
            key={x.label + x.url}
            role="listitem"
            className="social-btn"
            data-brand={brand}
            data-magnetic
            href={x.url}
            {...(external ? { target: '_blank', rel: 'noopener noreferrer' } : {})}
            aria-label={`${x.label}${external ? ' (opens in a new tab)' : ''}`}
          >
            <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
              {ICONS[brand]}
            </svg>
            <span className="tip" aria-hidden="true">{x.label}</span>
          </a>
        );
      })}
    </div>
  );
}
